from phon_verbs import card, cloze, choice, translate

def ex(title, note, pairs, cols=""):
    g = {"name": title, "note": note, "items": [card(a, b) for a, b in pairs]}
    if cols:
        g["cols"] = cols
    return g

def quiz(title, items, note="Type or choose the answer. Accents count, but a missing accent is marked as close and still saved."):
    g = {"name": title, "quiz": items, "note": note}
    return g

def L(num, name, summary, groups):
    return {
        "id": "gr-%s" % num,
        "label": "Chapitre %s" % num,
        "name": name,
        "summary": summary,
        "original": True,
        "groups": groups,
    }

