def lesson(i, level, label, name, summary, note, pairs, quizzes):
    return {
        "id": i, "level": level, "label": label, "name": name,
        "summary": summary, "original": True,
        "groups": [
            {"name": "Lire et écouter", "note": note, "items": [card(a, b) for a, b in pairs]},
            {"name": "Exercices", "quiz": quizzes,
             "note": "Check yourself. A missing accent counts as close and is still saved."},
        ],
    }


def book(i, name, short, color, levels, blurb, lessons):
    return {"id": i, "name": name, "short": short, "color": color,
            "levels": levels, "placeholder": False, "blurb": blurb, "lessons": lessons}


def spread(ids, n):
    buckets = [[] for _ in range(n)]
    for i, x in enumerate(ids):
        buckets[i % n].append(x)
    return buckets


