from phon_verbs import card, cloze, choice, translate

def words(title, pairs, note=""):
    g = {"name": title, "cols": "two", "items": [card(a, b) for a, b in pairs]}
    if note:
        g["note"] = note
    return g

def quiz(title, items, note="Answers are saved in this browser."):
    g = {"name": title, "quiz": items}
    if note:
        g["note"] = note
    return g

def unit(n, name, summary, groups, pages=None):
    d = {
        "id": "vp-%d" % n,
        "label": "Unité %d" % n,
        "name": name,
        "summary": summary,
        "original": True,
        "groups": groups,
    }
    if pages:
        d["bookpages"] = pages
    return d

